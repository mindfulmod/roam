// Checks the app's cities against seeds/coverage.json (top tourist countries, most-visited
// cities and holy cities) and writes seeds/coverage-report.md listing what is missing.
//   node scripts/coverage.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const want = read('seeds/coverage.json');
const meta = read('data/meta.json');

const norm = (s) =>
  String(s || '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

// Every name a city answers to, and every place inside it (so day trips count).
const cities = meta.cityOrder.map((id) => read(`data/cities/${id}.json`));
const cityNames = new Map();
const placeNames = new Map();
for (const c of cities) {
  const names = [c.id.replace(/-/g, ' '), c.wiki, c.coverWiki, ...c.name.split(/ · |, /)];
  for (const n of names) if (n) cityNames.set(norm(n), c.id);
  // Day trips count by their own title only: "Toledo, Spain" or "Bilbao" match, "Bath House" does not.
  const bare = (t) => String(t || '').replace(/ \(.*\)$/, '').replace(/,.*$/, '');
  for (const p of c.items.filter((p) => p.kind === 'see'))
    for (const n of [p.name, p.wiki, bare(p.wiki), bare(p.name), p.excursion && p.area]) if (n) placeNames.set(norm(n), c.id);
}
const find = (name) => {
  const n = norm(name);
  if (cityNames.has(n)) return { city: cityNames.get(n), as: 'city' };
  if (placeNames.has(n)) return { city: placeNames.get(n), as: 'day trip' };
  return null;
};

const out = ['# City coverage report', '', `Generated by \`node scripts/coverage.mjs\` from \`seeds/coverage.json\`. ${cities.length} cities in the app.`, ''];
let missing = 0;
let total = 0;

out.push('## Countries', '', '| # | Country | Covered | Missing |', '|---|---|---|---|');
want.countries.forEach(([country, list], i) => {
  const have = [];
  const lack = [];
  for (const name of list) {
    total++;
    const f = find(name);
    if (f) have.push(f.as === 'city' ? name : `${name} (in ${f.city})`);
    else (lack.push(name), missing++);
  }
  out.push(`| ${i + 1} | ${country} | ${have.join(', ') || '-'} | ${lack.join(', ') || 'none'} |`);
});

const section = (title, list) => {
  const lack = list.filter((n) => !find(n));
  total += list.length;
  missing += lack.length;
  out.push('', `## ${title}`, '', `${list.length - lack.length} of ${list.length} covered.`, '', lack.length ? `Missing: ${lack.join(', ')}.` : 'Nothing missing.');
};
section('Most-visited cities', want.cities);
section('Holy and pilgrimage cities', want.holy.map(([n]) => n));
out.push('', '### Holy cities notes', '', ...want.holy.map(([n, faith, note]) => `- **${n}** (${faith}): ${note}`));

out.splice(3, 0, `${total - missing} of ${total} names covered, ${missing} missing.`, '');
fs.writeFileSync(path.join(root, 'seeds/coverage-report.md'), out.join('\n') + '\n');
console.log(`${total - missing} of ${total} covered, ${missing} missing. See seeds/coverage-report.md`);
